// Generates src/data/area-centers.generated.ts: an approximate centre for every
// province and district, used to estimate distance for places without a pin
// (services that visit, or listings without a Google Maps link).
//
// Source: OpenStreetMap Nominatim (© OpenStreetMap contributors, ODbL).
// Run with:  node scripts/gen-area-centers.mjs
// It makes ~1,000 requests at 1 per second (Nominatim usage policy), so it
// takes about 17 minutes. Answers are kept in .area-centers-cache.json so a
// re-run only asks for what is missing.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const cacheFile = join(root, '.area-centers-cache.json')
const cache = existsSync(cacheFile) ? JSON.parse(readFileSync(cacheFile, 'utf8')) : {}

// Read provinces and districts back out of the generated areas file.
const src = readFileSync(join(root, 'src/data/thailand.generated.ts'), 'utf8')
const provinces = []
for (const block of src.split(/\n  \{\n/).slice(1)) {
  const [, slug, name] = block.match(/slug: '([^']+)',\s*name: '([^']+)'/)
  const districts = [...block.matchAll(/\{ slug: '([^']+)', name: '([^']+)' \}/g)].map((m) => ({
    slug: m[1],
    name: m[2],
  }))
  provinces.push({ slug, name, districts })
}

const fullProvince = (p) => (p.slug === 'bangkok' ? 'กรุงเทพมหานคร' : `จังหวัด${p.name}`)
const inThailand = (lat, lng) => lat > 4 && lat < 22 && lng > 96 && lng < 107
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function search(q) {
  const url = `https://nominatim.openstreetmap.org/search?format=jsonv2&countrycodes=th&accept-language=th&limit=1&q=${encodeURIComponent(q)}`
  for (let i = 0; i < 3; i++) {
    await sleep(1100)
    try {
      const res = await fetch(url, {
        headers: { 'User-Agent': 'SawasdeeDog/1.0 (+https://sawasdeedog.com)' },
      })
      if (!res.ok) continue
      const [hit] = await res.json()
      if (!hit) return null
      const lat = +(+hit.lat).toFixed(4)
      const lng = +(+hit.lon).toFixed(4)
      return inThailand(lat, lng) ? [lat, lng] : null
    } catch {}
  }
  return null
}

async function centre(key, queries) {
  if (cache[key]) return cache[key]
  for (const q of queries) {
    const found = await search(q)
    if (found) {
      cache[key] = found
      writeFileSync(cacheFile, JSON.stringify(cache))
      return found
    }
  }
  console.warn('not found:', key)
  return null
}

const out = {}
for (const p of provinces) {
  const prov = fullProvince(p)
  const pc = await centre(p.slug, [prov, p.name])
  if (pc) out[p.slug] = pc
  for (const d of p.districts) {
    const prefix = p.slug === 'bangkok' ? 'เขต' : 'อำเภอ'
    const c = await centre(`${p.slug}/${d.slug}`, [`${prefix}${d.name}, ${prov}`, `${d.name}, ${prov}`])
    if (c) out[`${p.slug}/${d.slug}`] = c
  }
  console.log(p.slug, 'done')
}

const lines = Object.entries(out).map(([k, [lat, lng]]) => `  '${k}': [${lat}, ${lng}],`)
writeFileSync(
  join(root, 'src/data/area-centers.generated.ts'),
  `// Generated by scripts/gen-area-centers.mjs. Do not edit by hand.
// Approximate centres from OpenStreetMap Nominatim (© OpenStreetMap contributors).
// ${lines.length} areas.

export const areaCenters: Record<string, [lat: number, lng: number]> = {
${lines.join('\n')}
}
`,
)
console.log('wrote', lines.length)
