// Downloads one photo per breed for the /farm pages: the lead image of the
// breed's English Wikipedia article, from Wikimedia Commons. Saves a 400px
// square WebP to public/breeds/<slug>.webp and the author and licence to
// src/data/breed-photos.generated.ts, so every photo can be credited.
//
// Run with:  node scripts/gen-breed-photos.mjs [slug ...]
// Photos already on disk are skipped; delete one to fetch it again.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import sharp from 'sharp'

const root = new URL('..', import.meta.url).pathname
const outDir = join(root, 'public/breeds')
const dataFile = join(root, 'src/data/breed-photos.generated.ts')
const UA = { 'User-Agent': 'SawasdeeDog/1.0 (+https://sawasdeedog.com)' }

// Article titles that differ from the English breed name.
const ARTICLE = {
  pomeranian: 'Pomeranian dog',
  samoyed: 'Samoyed dog',
  chihuahua: 'Chihuahua dog',
  maltese: 'Maltese dog',
  papillon: 'Papillon dog',
  'saint-bernard': 'St. Bernard dog',
  boxer: 'Boxer dog',
  dalmatian: 'Dalmatian dog',
  'thai-bangkaew': 'Thai Bangkaew Dog',
  'pembroke-welsh-corgi': 'Pembroke Welsh Corgi',
  'english-bulldog': 'Bulldog',
  'bichon-frise': 'Bichon Frisé',
  dachshund: 'Dachshund',
  'miniature-schnauzer': 'Miniature Schnauzer',
  'american-bully': 'American Bully',
}

// Commons files to use instead of the article's lead image (collages, odd crops).
const FILE = {
  'akita-inu': 'Akita Inu dog.jpg',
  'belgian-malinois': 'Malinois portrait.jpg',
  'shih-tzu': 'Shih Tzu portrait show dog.jpg',
  'labrador-retriever': 'Labrador Retriever - Yellow.JPG',
}

// Crop anchor where the default ("attention") cuts the dog's head off.
const CROP = { 'labrador-retriever': 'north' }

const src = readFileSync(join(root, 'src/data/breeds.ts'), 'utf8')
const breeds = [...src.matchAll(/slug: '([^']+)',\s*name: '[^']+',\s*nameEn: '([^']+)'/g)].map((m) => ({
  slug: m[1],
  nameEn: m[2],
}))

// Keep credits already collected.
const credits = {}
if (existsSync(dataFile)) {
  for (const m of readFileSync(dataFile, 'utf8').matchAll(/^ {2}'([^']+)': (\{.*\}),$/gm))
    credits[m[1]] = JSON.parse(m[2])
}

const only = new Set(process.argv.slice(2))
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const strip = (html = '') =>
  html
    .replace(/<[^>]+>/g, '')
    // Wiki links left in some author fields: [[User:x|name]] -> name, ([[User talk:x|talk]]) dropped.
    .replace(/\(\[\[User talk:[^\]]*\]\]\)/g, '')
    .replace(/\[\[[^\]|]*\|([^\]]*)\]\]/g, '$1')
    .replace(/\[\[([^\]]*)\]\]/g, '$1')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim()

async function json(url) {
  const res = await fetch(url, { headers: UA })
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  return res.json()
}

mkdirSync(outDir, { recursive: true })
for (const b of breeds) {
  if (only.size && !only.has(b.slug)) continue
  const file = join(outDir, `${b.slug}.webp`)
  if (existsSync(file) && credits[b.slug]) continue
  try {
    let fileName = FILE[b.slug]
    if (!fileName) {
      const title = ARTICLE[b.slug] ?? b.nameEn
      const summary = await json(
        `https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title.replace(/ /g, '_'))}`,
      )
      const original = summary.originalimage?.source
      if (!original) throw new Error('no lead image')
      // Large originals come back as a thumbnail path: .../thumb/x/xy/File.jpg/3840px-File.jpg
      const parts = new URL(original).pathname.split('/')
      fileName = decodeURIComponent(parts.includes('thumb') ? parts[parts.length - 2] : parts.at(-1))
    }
    const info = await json(
      `https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url|extmetadata&iiurlwidth=800&titles=${encodeURIComponent(`File:${fileName}`)}`,
    )
    const page = Object.values(info.query.pages)[0]
    const ii = page.imageinfo?.[0]
    if (!ii) throw new Error('no image info')
    const meta = ii.extmetadata ?? {}
    const img = Buffer.from(await (await fetch(ii.thumburl ?? ii.url, { headers: UA })).arrayBuffer())
    await sharp(img)
      .resize(400, 400, { fit: 'cover', position: CROP[b.slug] ?? 'attention' })
      .webp({ quality: 78 })
      .toFile(file)
    credits[b.slug] = {
      author: strip(meta.Artist?.value) || 'Wikimedia Commons',
      license: strip(meta.LicenseShortName?.value) || 'see source',
      source: ii.descriptionurl,
    }
    console.log('ok', b.slug, credits[b.slug].license)
  } catch (err) {
    console.warn('skip', b.slug, err.message)
  }
  await sleep(500)
}

const lines = Object.keys(credits)
  .sort()
  .map((k) => `  '${k}': ${JSON.stringify(credits[k])},`)
writeFileSync(
  dataFile,
  `// Generated by scripts/gen-breed-photos.mjs. Do not edit by hand.
// Breed photos in public/breeds/, from Wikimedia Commons, with their credits.

export type BreedPhoto = { author: string; license: string; source: string }

export const breedPhotos: Record<string, BreedPhoto> = {
${lines.join('\n')}
}
`,
)
console.log('wrote', lines.length)
